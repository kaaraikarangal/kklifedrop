/**
 * Normalizes state names (e.g. "Pondicherry" from Postal API -> "Puducherry")
 */
export function normalizeStateName(rawState?: string): string {
  if (!rawState) return "Puducherry";
  const s = rawState.trim();
  const lower = s.toLowerCase();
  if (lower === "pondicherry" || lower === "puducherry") return "Puducherry";
  if (lower === "tamilnadu" || lower === "tamil nadu") return "Tamil Nadu";
  if (lower === "orissa" || lower === "odisha") return "Odisha";
  if (lower === "uttaranchal" || lower === "uttarakhand") return "Uttarakhand";

  // Find case-insensitive match from ALL_STATES
  const match = ALL_STATES.find((st) => st.toLowerCase() === lower);
  return match || s;
}

/**
 * Normalizes district names from Postal API or user input to match dataset
 */
export function normalizeDistrictName(state: string, rawDistrict?: string): string {
  if (!rawDistrict) return "";
  const d = rawDistrict.trim();
  const districts = DISTRICTS_BY_STATE[state] || [];
  const lower = d.toLowerCase();

  const match = districts.find(
    (dist) =>
      dist.toLowerCase() === lower ||
      dist.toLowerCase().includes(lower) ||
      lower.includes(dist.toLowerCase())
  );
  return match || d;
}

